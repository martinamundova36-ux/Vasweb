// Generate distinct entry documents from the existing portal; business logic stays in one source.
import {readFileSync,writeFileSync,mkdirSync} from 'node:fs';
const source=readFileSync('student-house-portal/index.html','utf8');
for(const [mode,title] of [['student','Študentské prihlásenie'],['admin','Administrácia Student House Bratislava'],['questionnaire','Krok 2 – Osobný dotazník']]){
 const folder='student-house-portal/'+mode;mkdirSync(folder,{recursive:true});
 const html=source.replace('<body>','<body data-portal-entry="'+mode+'">').replace(/<title>.*?<\/title>/,'<title>'+title+' | Student House Bratislava by WEBU</title>');
 const output='<!-- GENERATED by scripts/build-student-house-entries.mjs; edit the parent index.html -->\n'+html;
 if(process.argv.includes('--check')){if(readFileSync(folder+'/index.html','utf8')!==output)throw Error('Stale entry: '+mode);}
 else writeFileSync(folder+'/index.html',output);
}
